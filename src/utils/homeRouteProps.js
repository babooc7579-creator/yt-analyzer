const toArray = (items) => (Array.isArray(items) ? items : []);

export function buildHomeRouteProps({
  clearRadarDecisions,
  discoveryCandidateCount,
  discoveryRightsWarningCount,
  isVideoSaved,
  latestScanText,
  loadStoredVideosForSelectedChannels,
  markRadarVideoStatus,
  openCreatorView,
  openRadarCandidateCount,
  productionCandidateCount,
  productionFocusCount,
  promoteVideoToProduction,
  restoreVideoToRadar,
  savedChannels,
  savedVideos,
  selectedChannelIds = [],
  toggleScrapVideo,
  ttoTtoAssetCount,
  videoUserRecords,
  videos,
}) {
  const selectedChannels = toArray(selectedChannelIds);

  return {
    clearRadarDecisions,
    discoveryCandidateCount,
    discoveryRightsWarningCount,
    isVideoSaved,
    latestScanText,
    loadStoredVideosForSelectedChannels,
    markRadarVideoStatus,
    onOpenView: openCreatorView,
    openRadarCandidateCount,
    productionCandidateCount,
    productionFocusCount,
    promoteVideoToProduction,
    restoreVideoToRadar,
    savedChannels,
    savedVideos,
    selectedChannelCount: selectedChannels.length,
    selectedChannelKey: [...selectedChannels].sort().join('|'),
    toggleScrapVideo,
    ttoTtoAssetCount,
    videoUserRecords,
    videos,
  };
}
