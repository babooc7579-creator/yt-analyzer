import { isChannelScannable } from '../constants/status';
import { getChannelScanDisplay } from './channelScanDisplay';

const toArray = (items) => (Array.isArray(items) ? items : []);

const toChannelList = (channels) => (
  toArray(channels).filter(channel => channel && typeof channel === 'object')
);

const getScannableChannelCountForCategory = (channels, category) => (
  toChannelList(channels).filter(channel => (
    channel.tags?.includes(category) && isChannelScannable(channel)
  )).length
);

export function getLegacyChannelPanelViewProps({
  addMode,
  apiKey,
  bulkInput,
  bulkLoading,
  bulkResult,
  cancelChannelPreview,
  cancelRenameCategory,
  categories,
  channelPreview,
  channelsLoading,
  cloudOnlyTags,
  confirmRenameCategory,
  error,
  handleBulkAdd,
  handlePreviewChannel,
  handleSaveChannel,
  handleTagScan,
  isEditingCategory,
  isScanning,
  loading,
  newCategoryName,
  newChannelInput,
  newChannelLang,
  newChannelNote,
  newChannelTags,
  onChangeApiKey,
  onDeleteChannel,
  onLoadStoredVideos,
  onOpenNotes,
  onToggleChannelSelection,
  onUpdateChannelMetadata,
  operationStage,
  previewLoading,
  progressMsg,
  renameLoading,
  renameValue,
  renamingCategory,
  resetBulkAdd,
  savedChannels,
  scanningTag,
  selectedCategoryTab,
  selectedChannelIds,
  setAddMode,
  setBulkInput,
  setCategories,
  setIsEditingCategory,
  setNewCategoryName,
  setNewChannelInput,
  setNewChannelLang,
  setNewChannelNote,
  setRenameValue,
  setSelectedCategoryTab,
  showWorkPanel,
  startRenameCategory,
  toggleNewChannelTag,
  updatingChannelId,
}) {
  const categoryList = toArray(categories);
  const channelList = toChannelList(savedChannels);
  const selectedChannels = toArray(selectedChannelIds);

  return {
    channelAddFormProps: {
      addMode,
      bulkInput,
      bulkLoading,
      bulkResult,
      cancelChannelPreview,
      cancelRenameCategory,
      categories: categoryList,
      channelPreview,
      cloudOnlyTags,
      confirmRenameCategory,
      handleBulkAdd,
      handlePreviewChannel,
      handleSaveChannel,
      isEditingCategory,
      loading,
      newCategoryName,
      newChannelInput,
      newChannelLang,
      newChannelNote,
      newChannelTags,
      previewLoading,
      renameLoading,
      renameValue,
      renamingCategory,
      resetBulkAdd,
      setAddMode,
      setBulkInput,
      setCategories,
      setIsEditingCategory,
      setNewCategoryName,
      setNewChannelInput,
      setNewChannelLang,
      setNewChannelNote,
      setRenameValue,
      startRenameCategory,
      toggleNewChannelTag,
    },
    operationStage,
    channelListProps: {
      channels: channelList,
      channelsLoading,
      getScanDisplay: getChannelScanDisplay,
      onDelete: onDeleteChannel,
      onOpenNotes,
      onToggleSelection: onToggleChannelSelection,
      onUpdateMetadata: onUpdateChannelMetadata,
      selectedCategory: selectedCategoryTab,
      selectedChannelIds: selectedChannels,
      updatingChannelId,
    },
    footerProps: {
      error,
      loading,
      onLoadStoredVideos,
      progressMsg,
      selectedChannelCount: selectedChannels.length,
    },
    introProps: {
      apiKey,
      onChangeApiKey,
    },
    showWorkPanel,
    tagTabsProps: {
      categories: categoryList,
      channels: channelList,
      getScannableChannelCount: (category) => getScannableChannelCountForCategory(channelList, category),
      isScanning,
      onScanTag: handleTagScan,
      onSelectCategory: setSelectedCategoryTab,
      scanningTag,
      selectedCategory: selectedCategoryTab,
    },
  };
}
